with torch.no_grad():
    img_feat = model.encode_image(img)
    txt_feat = model.encode_text(txt)
    img_feat = F.normalize(img_feat, dim=-1, p=2)
    txt_feat = F.normalize(txt_feat, dim=-1, p=2)
    scores = (100.0 * img_feat @ txt_feat.T).softmax(dim=-1)

