def collate_fn(batch):
    return {
        "images": torch.stack([b["pixel_values"] for b in batch]).float(),
        "input_ids": torch.stack([b["input_ids"] for b in batch])
    }

# # Create DataLoader
# train_loader = DataLoader(
#     train_dataset,
